// Writes Sources/PufferCore/EmojiData.swift to standard output from Unicode's
// emoji list and CLDR's English names and keywords. Run it through
// scripts/update-emoji.sh, which downloads the files.
//
//   swift scripts/generate-emoji.swift emoji-test.txt annotations.xml annotationsDerived.xml
//
// Keeps fully-qualified emoji up to Emoji 15.0 (what macOS 14, Puffer's
// minimum, can draw), without skin tones and without the Component group.

import Foundation

let maxVersion = 15.0
let skinTones: ClosedRange<UInt32> = 0x1F3FB...0x1F3FF

func fail(_ message: String) -> Never {
    FileHandle.standardError.write(Data((message + "\n").utf8))
    exit(1)
}

let arguments = CommandLine.arguments.dropFirst()
guard arguments.count == 3 else {
    fail("usage: generate-emoji.swift emoji-test.txt annotations.xml annotationsDerived.xml")
}
let paths = Array(arguments)

/// CLDR leaves out U+FE0F; look emoji up without it.
func key(_ emoji: String) -> String {
    String(String.UnicodeScalarView(emoji.unicodeScalars.filter { $0.value != 0xFE0F }))
}

final class Annotations: NSObject, XMLParserDelegate {
    var names: [String: String] = [:]
    var keywords: [String: [String]] = [:]
    private var cp: String?
    private var isName = false
    private var text = ""

    func read(_ path: String) {
        guard let parser = XMLParser(contentsOf: URL(fileURLWithPath: path)) else { fail("cannot read \(path)") }
        parser.delegate = self
        guard parser.parse() else { fail("cannot parse \(path): \(String(describing: parser.parserError))") }
    }

    func parser(_ parser: XMLParser, didStartElement element: String, namespaceURI: String?,
                qualifiedName: String?, attributes: [String: String]) {
        guard element == "annotation", let cp = attributes["cp"] else { return }
        self.cp = key(cp)
        isName = attributes["type"] == "tts"
        text = ""
    }

    func parser(_ parser: XMLParser, foundCharacters string: String) {
        if cp != nil { text += string }
    }

    func parser(_ parser: XMLParser, didEndElement element: String, namespaceURI: String?, qualifiedName: String?) {
        guard element == "annotation", let cp else { return }
        let value = text.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        if isName {
            names[cp] = names[cp] ?? value
        } else if keywords[cp] == nil {
            keywords[cp] = value.split(separator: "|").map { $0.trimmingCharacters(in: .whitespaces) }
        }
        self.cp = nil
    }
}

let annotations = Annotations()
annotations.read(paths[1])
annotations.read(paths[2])

guard let list = try? String(contentsOfFile: paths[0], encoding: .utf8) else { fail("cannot read \(paths[0])") }

var header: [String] = []
var group = ""
var lines: [String] = []
var seen = Set<String>()

for line in list.split(separator: "\n", omittingEmptySubsequences: false) {
    if line.hasPrefix("# Version:") || line.hasPrefix("# Date:") {
        header.append(line.dropFirst(2).trimmingCharacters(in: .whitespaces))
    }
    if line.hasPrefix("# group:") {
        group = line.dropFirst("# group:".count).trimmingCharacters(in: .whitespaces)
        continue
    }
    guard group != "Component", !line.hasPrefix("#"),
          let semicolon = line.firstIndex(of: ";"), let hash = line.firstIndex(of: "#") else { continue }
    let status = line[line.index(after: semicolon)..<hash].trimmingCharacters(in: .whitespaces)
    guard status == "fully-qualified" else { continue }

    // "🌳 E1.0 deciduous tree"
    let comment = line[line.index(after: hash)...].trimmingCharacters(in: .whitespaces)
    let parts = comment.split(separator: " ", maxSplits: 2)
    guard parts.count == 3, parts[1].hasPrefix("E"), let version = Double(parts[1].dropFirst()) else {
        fail("unexpected line: \(line)")
    }
    let character = String(parts[0])
    guard version <= maxVersion,
          !character.unicodeScalars.contains(where: { skinTones.contains($0.value) }),
          seen.insert(character).inserted else { continue }

    let name = annotations.names[key(character)] ?? parts[2].lowercased()
    let nameWords = Set(name.split(separator: " ").map(String.init))
    var keywords: [String] = []
    for keyword in annotations.keywords[key(character)] ?? []
    where !keyword.isEmpty && keyword != name && !nameWords.contains(keyword) && !keywords.contains(keyword) {
        keywords.append(keyword)
    }
    for field in [name] + keywords where field.contains("\t") || field.contains("|") || field.contains("\n") {
        fail("separator inside \(character): \(field)")
    }
    lines.append("\(character)\t\(name)\t\(keywords.joined(separator: "|"))")
}

guard lines.count > 1000 else { fail("only \(lines.count) emoji; is the input right?") }

print("""
// Generated by scripts/update-emoji.sh from Unicode's emoji-test.txt and
// CLDR's English annotations. Do not edit; rerun the script.
// \(header.joined(separator: ", ")); \(lines.count) emoji up to Emoji \(maxVersion).
//
// One emoji per line: the emoji, its name, then keywords separated by "|".

extension EmojiCatalog {
    static let data = #\"\"\"
\(lines.joined(separator: "\n"))
\"\"\"#
}
""")
